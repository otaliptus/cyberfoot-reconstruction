import assert from 'node:assert/strict';import fs from 'node:fs';
import {readSave,record,writeSave,shortString} from '../save-format.mjs';
import {selectAuctionLot} from '../auction.mjs';
import {OriginalRandom} from '../match-core.mjs';
import {auctionWindowView,auctionLanguageText,createAuctionSession,formatAuctionMoney} from '../auction-window.mjs';

const save=readSave(fs.readFileSync(new URL('./original-career.s15',import.meta.url))),language=JSON.parse(fs.readFileSync(new URL('../language.json',import.meta.url))),v=bytes=>new DataView(bytes.buffer,bytes.byteOffset,bytes.byteLength);
const rng=new OriginalRandom(1),runtime={auctionBasePrice:100};
selectAuctionLot(save,runtime,{rng});
assert.ok(runtime.auctionPlayer>=0,'scripted lot selected from the real career');
const playerId=runtime.auctionPlayer,sellerId=runtime.auctionSellerClub;
const before=writeSave(save);
const view=auctionWindowView(save,runtime,{language});
assert.equal(view.form,'Form23');
assert.equal(view.title,language[0x170].text);
assert.equal(view.Label12,language[0x170].text);
assert.equal(view.chbutton1,language[0x177].text);
assert.equal(view.Label2,language[0x173].text);
assert.equal(view.Label4,language[0x176].text);
assert.equal(view.Label7,language[0x178].text);
assert.equal(view.Label17,language[0x179].text);
assert.equal(view.jlnome,shortString(record(save,'players',playerId),0,20));
assert.equal(view.sellerName,shortString(record(save,'clubs',sellerId),0,25));
const roleLanguageIds=[143,147,145,149,151];
assert.equal(view.jlpos,language[roleLanguageIds[v(record(save,'players',playerId)).getInt32(0x24,true)]].text);
assert.equal(view.jlpais,language[786+v(record(save,'players',playerId)).getInt32(0x1c,true)].text);
assert.equal(view.jlpasse,formatAuctionMoney(100));
assert.equal(view.player.id,playerId);
assert.ok(view.player.strength>0&&view.player.age>0);
assert.ok(view.Label15.startsWith(language[0x133].text));
assert.ok(view.startCaption.startsWith(language[0x38c].text)&&view.startCaption.includes(' '));
assert.deepEqual(writeSave(save),before,'auctionWindowView leaves the save untouched');
const sparse=auctionWindowView(save,runtime,{language:{}});
assert.equal(sparse.Label12,'368');
assert.equal(sparse.chbutton1,'375');
assert.equal(auctionLanguageText({},0x170),'368');

const results=[],events=[];
const session=createAuctionSession({save,runtime,rng,language,onFinished:result=>results.push(result),onEvent:event=>events.push(event)});
session.start();
assert.equal(runtime.auctionHighestBid??0,0);
assert.ok(runtime.auctionCurrentClub>=0);
assert.equal(session.view().currentClubId,runtime.auctionCurrentClub);
const invalid=session.bid('not a number');
assert.equal(invalid.outcome,'invalid');
assert.equal(runtime.auctionHighestBid??0,0);
const accepted=session.bid('500');
assert.equal(accepted.outcome,'resolved');
assert.equal(runtime.auctionHighestBid,500000);
assert.equal(runtime.auctionHighestBidder,runtime.auctionCurrentClub);
assert.equal(results.length,1);
const result=results[0];
assert.equal(session.finished,true);
assert.equal(result.sold,true);
assert.ok(result.buyer>=0&&result.price>0);
assert.equal(v(record(save,'players',playerId)).getInt32(0x20,true),result.buyer);
assert.ok(events.some(event=>event.event==='start'),'start event recorded');
assert.ok(events.some(event=>event.event==='bid'&&event.outcome==='resolved'),'accepted bid recorded');
assert.ok(events.some(event=>event.event==='resolve'),'resolution recorded');
assert.ok(events.some(event=>event.event==='finalize'&&event.accept===true),'finalization recorded');
assert.equal(session.bid('999').outcome,'finished');
console.log(`Auction window: real-save lot ${playerId} (${view.jlnome}) bid to ${formatAuctionMoney(runtime.auctionHighestBid)}, resolved and sold to club ${result.buyer} for ${formatAuctionMoney(result.price)}; view, language fallback and host result passed.`);
