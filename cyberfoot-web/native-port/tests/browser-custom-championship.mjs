import {chromium} from 'playwright';
import assert from 'node:assert/strict';

const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1280,height:800}});
const errors=[];
page.on('pageerror',error=>errors.push(String(error)));
page.on('console',message=>{if(message.type()==='error')errors.push('console: '+message.text());});
await page.goto('http://127.0.0.1:8766/game.html?manualClock=1&automaticInteractions=1');
await page.waitForFunction(()=>window.gameShell?.form==='Form1');
await page.evaluate(()=>window.gameShell.showGameSettings());
await page.waitForFunction(()=>window.gameShell.form==='Form9');
await page.evaluate(()=>window.gameShell.openChampionship());
await page.waitForFunction(()=>window.gameShell.form==='Form39');
const countryPoint=await page.evaluate(()=>{const renderer=window.gameShell.renderer,target=renderer.hitTargets.find(entry=>entry.name==='list1'&&entry.operation&&entry.value===3);if(!target)throw Error('Germany country row not visible');const rect=renderer.canvas.getBoundingClientRect();return {x:rect.left+(target.x+target.width/2)*rect.width/renderer.canvas.width,y:rect.top+(target.y+target.height/2)*rect.height/renderer.canvas.height};});
await page.mouse.click(countryPoint.x,countryPoint.y);
await page.waitForTimeout(150);
await page.evaluate(()=>window.gameShell.click('bt1'));
await page.waitForFunction(()=>window.gameShell.form==='Form11');
assert.equal(await page.evaluate(()=>window.gameShell.renderer.frame.custom),true);
assert.ok(await page.evaluate(()=>window.gameShell.renderer.frame.clubs.length>=20));
await page.evaluate(()=>window.gameShell.setField('Edit1','Custom Forms'));
await page.evaluate(()=>window.gameShell.click('button1'));
await page.waitForFunction(()=>window.gameShell.form==='Form13',{timeout:60000});
const hub=JSON.parse(await page.evaluate(()=>window.render_game_to_text()));
assert.equal(hub.form,'Form13');
await page.evaluate(()=>window.gameShell.click('btjogar'));
await page.waitForFunction(()=>window.gameShell.form==='Form87',{timeout:60000});
await page.evaluate(()=>window.gameShell.click('bt_irprojogo'));
await page.waitForFunction(()=>window.gameShell.form==='Form46',{timeout:60000});
const resultForm=await page.evaluate(async()=>window.gameShell.playMatchToResults());
assert.ok(['Form26','Form67'].includes(resultForm));
assert.deepEqual(await page.evaluate(()=>JSON.parse(window.render_game_to_text()).unhandled),[]);
assert.deepEqual(errors,[]);
await browser.close();
console.log('custom championship: Form39 -> Form11 -> playable career hub passed.');
