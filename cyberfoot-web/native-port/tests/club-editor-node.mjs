import assert from 'node:assert/strict';import fs from 'node:fs';
import {readSave,writeSave,record,shortString} from '../save-format.mjs';
import {renameClub,renameStadium,editClubLevel,editPlayerName,editPlayerAttribute,clubEditorView,CLUB_NAME_CAPACITY,PLAYER_AGE_MIN,PLAYER_AGE_MAX,PLAYER_SKILL_MAX} from '../club-editor.mjs';
const saveBytes=fs.readFileSync(new URL('./original-career.s15',import.meta.url)),language=JSON.parse(fs.readFileSync(new URL('../language.json',import.meta.url)));
const fresh=()=>readSave(saveBytes),view=(bytes)=>new DataView(bytes.buffer,bytes.byteOffset,bytes.byteLength);
const probe=fresh(),career=view(probe.career),clubId=career.getInt32(8,true);
assert.equal(probe.sections.find((s)=>s.name==='clubs').recordSize,760,'club recordSize 760');
assert.equal(probe.sections.find((s)=>s.name==='players').recordSize,304,'player recordSize 304');
const beforeClub=shortString(record(probe,'clubs',clubId),0,25);
const initial=clubEditorView({save:probe,clubId,language});
assert.equal(initial.form,'Form3');
assert.equal(initial.club.name,beforeClub);
assert.ok(initial.players.length>0,'human club has players');
const playerId=initial.players[0].id;
const beforePlayer=shortString(record(probe,'players',playerId),0,20);
const save=fresh();
assert.equal(renameClub(save,clubId,'Test FC Porto').name,'Test FC Porto');
assert.equal(shortString(record(save,'clubs',clubId),0,25),'Test FC Porto');
assert.equal(renameStadium(save,clubId,'Test Arena').name,'Test Arena');
assert.equal(shortString(record(save,'clubs',clubId),0x1d0,35),'Test Arena');
assert.equal(editClubLevel(save,clubId,18).level,18);
assert.equal(view(record(save,'clubs',clubId)).getInt32(0x98,true),18);
assert.equal(view(record(save,'clubs',clubId)).getInt32(0x94,true),view(record(fresh(),'clubs',clubId)).getInt32(0x94,true),'club-strength mirror 0x98 does not touch adjacent 0x94 (oracle: 0064e824/0064e750 strength thresholds)');
assert.equal(view(record(save,'clubs',clubId)).getInt32(0x9c,true),view(record(fresh(),'clubs',clubId)).getInt32(0x9c,true),'club-strength mirror 0x98 does not touch adjacent 0x9c');
assert.equal(editPlayerName(save,playerId,'Test Player').name,'Test Player');
assert.equal(shortString(record(save,'players',playerId),0,20),'Test Player');
assert.equal(editPlayerAttribute(save,playerId,{age:25,skill:42}).current.age,25);
assert.equal(view(record(save,'players',playerId)).getInt32(0x18,true),25);
assert.equal(view(record(save,'players',playerId)).getInt32(0x28,true),42);
assert.deepEqual(readSave(writeSave(save)).career,save.career,'career block round-trips');
assert.equal(shortString(record(readSave(writeSave(save)),'clubs',clubId),0,25),'Test FC Porto','club rename round-trips');
assert.equal(shortString(record(readSave(writeSave(save)),'players',playerId),0,20),'Test Player','player rename round-trips');
const replay=()=>{const target=fresh();renameClub(target,clubId,'Test FC Porto');renameStadium(target,clubId,'Test Arena');editClubLevel(target,clubId,18);editPlayerName(target,playerId,'Test Player');editPlayerAttribute(target,playerId,{age:25,skill:42});return writeSave(target);};
assert.deepEqual(replay(),writeSave(save),'club-editor flow is deterministic');
const bounds=fresh();
assert.throws(()=>renameClub(bounds,clubId,'X'.repeat(CLUB_NAME_CAPACITY+1)),/exceeds 25/,'club name bound rejects');
assert.throws(()=>renameStadium(bounds,clubId,'Y'.repeat(31)),/30/,'stadium editor bound rejects');
assert.throws(()=>editClubLevel(bounds,clubId,26),/0\.\.25/,'club level bound rejects');
assert.throws(()=>editClubLevel(bounds,clubId,-1),/0\.\.25/,'club level low bound rejects');
assert.throws(()=>editPlayerAttribute(bounds,playerId,{age:PLAYER_AGE_MIN-1}),/16\.\.42/,'player age low bound rejects');
assert.throws(()=>editPlayerAttribute(bounds,playerId,{age:PLAYER_AGE_MAX+1}),/16\.\.42/,'player age high bound rejects');
assert.throws(()=>editPlayerAttribute(bounds,playerId,{skill:PLAYER_SKILL_MAX+1}),/0\.\.100/,'player skill bound rejects');
assert.throws(()=>editPlayerAttribute(bounds,playerId,{role:5}),/0\.\.4/,'player role bound rejects');
assert.throws(()=>editPlayerName(bounds,playerId,'Z'.repeat(31)),/30/,'player dialog bound rejects');
assert.equal(shortString(record(bounds,'clubs',clubId),0,25),beforeClub,'failed edits leave the save untouched');
assert.equal(shortString(record(bounds,'players',playerId),0,20),beforePlayer,'failed player edits leave the save untouched');
console.log(`Club editor Form3: club ${clubId} ${beforeClub}->Test FC Porto, player ${playerId} ${beforePlayer}->Test Player age 25 skill 42, bounds 25/30/16..42/0..100 reject ok.`);
