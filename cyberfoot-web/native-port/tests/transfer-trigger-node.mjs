import assert from 'node:assert/strict';import fs from 'node:fs';
import {readSave,writeSave,record} from '../save-format.mjs';
import {OriginalRandom} from '../match-core.mjs';
import {auctionStart} from '../auction.mjs';
import {originalPlayerValue} from '../player-value.mjs';
import {pendingAuctionOffer,pendingContractOffer,consumeAuctionOffer} from '../transfer-trigger.mjs';
const load=()=>readSave(fs.readFileSync(new URL('./original-career.s15',import.meta.url))),v=(b)=>new DataView(b.buffer,b.byteOffset,b.byteLength);
const save=load(),career=v(save.career),human=career.getInt32(8,true),day=career.getInt32(0x16c,true),before=writeSave(save);
assert.equal(career.getInt32(0x88,true),1);
const empty={};
assert.equal(pendingAuctionOffer(save,empty),null);
assert.equal(pendingAuctionOffer(save,{}),null);
const runtime={humanParticipation:true},rtBefore=JSON.stringify(runtime),offer=pendingAuctionOffer(save,runtime);
assert.ok(offer&&Number.isInteger(offer.player)&&offer.player>=0&&Number.isInteger(offer.basePrice)&&offer.basePrice>0);
assert.equal(JSON.stringify(runtime),rtBefore);
assert.deepEqual(writeSave(save),before);
assert.equal(v(record(save,'players',offer.player)).getInt32(0x20,true)!==human,true);
assert.equal(offer.basePrice,originalPlayerValue(save,offer.player)|0);
const probe={auctionPlayer:offer.player,auctionBasePrice:offer.basePrice},started=auctionStart(save,probe,{rng:new OriginalRandom(1)});
assert.equal(started.started,true);
assert.equal(probe.auctionFlag,1);
assert.equal(probe.auctionCurrentClub,human);
assert.deepEqual(writeSave(save),before);
assert.equal(pendingAuctionOffer(save,runtime)?.player,offer.player);
const cup=load();v(cup.career).setInt32(0x88,7,true);
assert.equal(pendingAuctionOffer(cup,runtime),null);
assert.equal(pendingAuctionOffer(cup,runtime),null);
const auto={humanParticipation:false};
assert.equal(pendingAuctionOffer(save,auto),null);
const blocked=load();v(record(blocked,'clubs',human)).setInt32(0x64,99,true);
assert.equal(pendingAuctionOffer(blocked,runtime),null);
const consumed={humanParticipation:true};assert.ok(pendingAuctionOffer(save,consumed));
consumeAuctionOffer(save,consumed);
assert.equal(consumed.auctionOfferDay,day);
assert.equal(consumed.auctionGate,0);
assert.equal(pendingAuctionOffer(save,consumed),null);
assert.equal(pendingAuctionOffer(save,consumed),null);
const contract=pendingContractOffer(save,runtime);
assert.ok(contract&&Number.isInteger(contract.player)&&Number.isInteger(contract.offer));
assert.equal(v(record(save,'players',contract.player)).getInt32(0x20,true),human);
assert.equal(contract.offer,Number(v(record(save,'players',contract.player)).getBigInt64(0x38,true)/10000n)|0);
assert.deepEqual(pendingContractOffer(save,runtime),contract);
assert.deepEqual(writeSave(save),before);
assert.equal(pendingContractOffer(cup,runtime),null);
assert.equal(pendingContractOffer(cup,runtime),null);
console.log(`Transfer trigger: auction lot ${offer.player} base ${offer.basePrice} starts via club ${human}, contract candidate ${contract.player} offer ${contract.offer}; post-results/national/consumed gates null deterministically.`);
