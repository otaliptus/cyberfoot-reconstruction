import {chromium} from '/Users/talip/.codex/skills/develop-web-game/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';import {mkdirSync,writeFileSync} from 'node:fs';
const output='/Users/talip/Documents/ChatGPT/misc/cyberfoot-web/output/game-shell';mkdirSync(output,{recursive:true});
const browser=await chromium.launch({headless:true}),page=await browser.newPage({viewport:{width:1280,height:800}}),errors=[];
page.on('pageerror',error=>errors.push(String(error)));page.on('console',message=>{if(message.type()==='error')errors.push('console: '+message.text());});
await page.goto('http://127.0.0.1:8766/game.html?manualClock=1&autoInteractions=1');
await page.waitForFunction(()=>window.gameShell&&window.gameShell.form==='Form1',{timeout:60000});
const boot=JSON.parse(await page.evaluate(()=>window.render_game_to_text()));
assert.equal(boot.ui,'vcl');assert.equal(boot.form,'Form1');assert.equal(boot.selector,'menu');
assert.equal(await page.evaluate(()=>getComputedStyle(document.getElementById('dev')).display),'none','dev overlay starts hidden');
assert.equal(await page.evaluate(()=>/dev overlay|Auction window \(Form23\)|Contract window|Season review/.test(document.body.innerText)),false,'no dev panel text is visible');
await page.screenshot({path:output+'/boot-main-menu.png'});
const clickControl=async name=>{
 const point=await page.evaluate(name=>{
  const renderer=window.gameShell.renderer,target=renderer.hitTargets.find(entry=>entry.name===name&&entry.operation);
  if(!target)return null;const rect=renderer.canvas.getBoundingClientRect();
  return {x:rect.left+(target.x+target.width/2)*rect.width/renderer.canvas.width,y:rect.top+(target.y+target.height/2)*rect.height/renderer.canvas.height};
 },name);
 if(!point)return page.evaluate(name=>window.gameShell.click(name),name);
 await page.mouse.click(point.x,point.y);
 return true;
};
await clickControl('Shape1');await page.waitForFunction(()=>window.gameShell.form==='Form9',{timeout:30000});
assert.equal(JSON.parse(await page.evaluate(()=>window.render_game_to_text())).form,'Form9');
await page.screenshot({path:output+'/new-game-settings.png'});
await clickControl('xibutton2');await page.waitForFunction(()=>window.gameShell.form==='Form11',{timeout:30000});
const selectTeam=JSON.parse(await page.evaluate(()=>window.render_game_to_text()));
assert.equal(selectTeam.form,'Form11');assert.equal(selectTeam.selector,'new-game');
await page.locator('[data-original-control="Form11.Edit1"]').fill('Shell Tester');
await page.screenshot({path:output+'/select-team.png'});
await clickControl('button1');await page.waitForFunction(()=>window.gameShell.form==='Form13',{timeout:60000});
const hub=JSON.parse(await page.evaluate(()=>window.render_game_to_text()));
assert.equal(hub.form,'Form13');assert.equal(hub.career.managerName,'Shell Tester');assert.equal(hub.round,1);
await page.screenshot({path:output+'/career-hub.png'});
await clickControl('btjogar');await page.waitForFunction(()=>window.gameShell.form==='Form87',{timeout:60000});
const lineup=JSON.parse(await page.evaluate(()=>window.render_game_to_text()));
assert.equal(lineup.form,'Form87');
await page.screenshot({path:output+'/lineup.png'});
await clickControl('bt_irprojogo');await page.waitForFunction(()=>window.gameShell.form==='Form46'&&!!window.gameShell.match,{timeout:30000});
assert.equal(JSON.parse(await page.evaluate(()=>window.render_game_to_text())).form,'Form46');
await page.screenshot({path:output+'/match.png'});
const resultsForm=await page.evaluate(async()=>await window.gameShell.playMatchToResults());
assert.equal(resultsForm,'Form67');
const results=JSON.parse(await page.evaluate(()=>window.render_game_to_text()));
assert.equal(results.form,'Form67');assert.equal(results.matchFailure,null);
assert.equal(results.unhandled.length,0,'no unhandled original operations');
await page.screenshot({path:output+'/results.png'});
await clickControl('bt3');await page.waitForFunction(()=>window.gameShell.form==='Form13',{timeout:60000});
await clickControl('btjogar');await page.waitForFunction(()=>JSON.parse(window.render_game_to_text()).rounds===1,{timeout:60000});
assert.equal(JSON.parse(await page.evaluate(()=>window.render_game_to_text())).continuations.length,1);
await page.evaluate(async()=>{await window.gameShell.openAuction();});
await page.waitForFunction(()=>window.gameShell.form==='Form23',{timeout:30000});
const auction=JSON.parse(await page.evaluate(()=>window.render_game_to_text()));
assert.equal(auction.form,'Form23');assert.equal(auction.screens.at(-1),'Form23');
await page.screenshot({path:output+'/auction.png'});
assert.deepEqual(errors,[]);
writeFileSync(output+'/checks.json',JSON.stringify({boot,selectTeam,hub,lineup,results,auction,errors},null,2));
await browser.close();console.log('Game shell: original VCL main menu drove New Game → settings → team → lineup → match → results → auction with real pointer clicks, no console errors and no dev overlay text.');
